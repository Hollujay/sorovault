package codegen

import (
	"fmt"
	"strings"

	"github.com/soroworks/sorovault/internal/model"
)

// Rust renders a Rust module for the given interface.
//
// The output follows soroban-sdk's contract client conventions,
// declaring types and a client using the contract's functions.
//
// The generated code:
// - Declares a type for each user-defined type in the interface
// - Exports a Client interface with one method per function
// - Uses the contract's ABI version
// - Uses field names as String types for user-defined types.
func Rust(iface *model.Interface, src Source) (string, error) {
	var b strings.Builder

	// Write header
	fmt.Fprintf(&b, "// Code generated by SoroVault from contract %s on %s.\n", src.ContractID, src.Network)
	fmt.Fprintf(&b, "// Interface version (WASM hash): %s\n", src.WasmHash)
	fmt.Fprintf(&b, "// AUTOGENERATED - DO NOT EDIT.\n\n")

	// Write user-defined types
	if len(iface.Types.Structs)+len(iface.Types.Unions)+len(iface.Types.Enums) > 0 {
		fmt.Fprintf(&b, "// User-defined types:\n\n")
	}

	// Struct types - use field names as types
	for _, s := range iface.Types.Structs {
		fmt.Fprintf(&b, "pub struct %s {\n", s.Name)
		for _, f := range s.Fields {
			fmt.Fprintf(&b, "\t%s: String,\n", f.Name)
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	// Union types
	for _, u := range iface.Types.Unions {
		fmt.Fprintf(&b, "pub enum %s {\n", u.Name)
		for _, c := range u.Cases {
			fmt.Fprintf(&b, "\t%s,\n", c.Name)
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	// Enum types
	for _, e := range iface.Types.Enums {
		fmt.Fprintf(&b, "pub enum %s {\n", e.Name)
		for _, c := range e.Cases {
			fmt.Fprintf(&b, "\t%s\n", c.Name)
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	// Write client
	fmt.Fprintf(&b, "// Client for interacting with the contract.\n")
	fmt.Fprintf(&b, "pub struct Client {\n")
	fmt.Fprintf(&b, "    // Contract address.\n")
	fmt.Fprintf(&b, "    address: String,\n")
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "/// Connect to a contract address.\n")
	fmt.Fprintf(&b, "pub fn connect(address: String) -> Self {\n")
	fmt.Fprintf(&b, "    Self {\n")
	fmt.Fprintf(&b, "        address\n")
	fmt.Fprintf(&b, "    }\n")
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "/// Returns the contract address.\n")
	fmt.Fprintf(&b, "pub fn address(&self) -> &String {\n")
	fmt.Fprintf(&b, "    &self.address\n")
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "/// Execute a function on the contract.\n")
	fmt.Fprintf(&b, "pub fn call(&self, fn_name: String, args: Vec<u8>) -> Result<Vec<u8>, soroban_sdk::Error> {\n")
	fmt.Fprintf(&b, "    let client = contractclient::Client::new(self.address);\n")
	fmt.Fprintf(&b, "    client.call(fn_name, args)\n")
	fmt.Fprintf(&b, "}\n")

	return b.String(), nil
}