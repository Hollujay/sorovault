var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// TypeScript renders a client module for iface.
//
// The output imports @stellar/stellar-sdk (v14 or later) and the buffer
// package, declares every user-defined type, and exports a typed Client
// interface and a connect function returning a contract.Client narrowed to
// it. Type mappings follow the conventions of the Stellar CLI's own
// TypeScript bindings, so values round-trip through the SDK unchanged.
func TypeScript(iface *model.Interface, src Source) (string, error) {
	g := &tsGen{errorEnums: map[string]bool{}}
	for _, e := range iface.Types.ErrorEnums {
		g.errorEnums[e.Name] = true
	}

	w := &g.b
	fmt.Fprintf(w, "// Code generated by SoroVault from contract %s on %s. DO NOT EDIT.\n", src.ContractID, src.Network)
	if iface.Builtin {
		fmt.Fprintf(w, "// Built-in interface identifier: %s\n", src.WasmHash)
	} else {
		fmt.Fprintf(w, "// Interface version (WASM hash): %s\n", src.WasmHash)
	}
	if iface.Meta != nil {
		if v := iface.Meta["rssdkver"]; v != "" {
			fmt.Fprintf(w, "// Built with soroban-sdk %s\n", oneLine(v))
		}
	}
	if d := src.Deprecation; d != nil {
		// A deprecation is tool-carrying information, so it goes in the
		// header where imports start reading, framed the way TypeScript
		// tooling reads it.
		fmt.Fprintf(w, "//\n// @deprecated since %s\n", d.Since)
		var line []string
		if d.Note != "" {
			line = append(line, oneLine(d.Note))
		}
		if d.Successor != "" {
			line = append(line, "Use contract "+d.Successor+" instead.")
		}
		if len(line) > 0 {
			fmt.Fprintf(w, "// %s\n", strings.Join(line, " "))
		}
	}
	if src.WithZod {
		// The schemas section imports zod below.
		w.WriteString("//\n// Requires @stellar/stellar-sdk >= 14, buffer and zod >= 3.\n\n")
		w.WriteString("import { Buffer } from \"buffer\";\n")
		fmt.Fprintf(w, "import * as sdk from %q;\n", sdkImport)
		w.WriteString("import { z } from \"zod\";\n\n")
	} else {
		w.WriteString("//\n// Requires @stellar/stellar-sdk >= 14 and buffer.\n\n")
		w.WriteString("import { Buffer } from \"buffer\";\n")
		fmt.Fprintf(w, "import * as sdk from %q;\n\n", sdkImport)
	}

	fmt.Fprintf(w, "export const contractId = %q;\n", src.ContractID)
	fmt.Fprintf(w, "export const networkName = %q;\n", src.Network)
	if iface.Builtin {
		fmt.Fprintf(w, "export const interfaceId = %q;\n", src.WasmHash)
	} else {
		fmt.Fprintf(w, "export const wasmHash = %q;\n", src.WasmHash)
	}

	for _, s := range sortedBy(iface.Types.Structs, func(s model.Struct) string { return s.Name }) {
		g.writeStruct(s)
	}
	for _, u := range sortedBy(iface.Types.Unions, func(u model.Union) string { return u.Name }) {
		g.writeUnion(u)
	}
	for _, e := range sortedBy(iface.Types.Enums, func(e model.Enum) string { return e.Name }) {
		g.writeEnum(e)
	}
	g.writeErrors(iface.Types.ErrorEnums)
	g.writeClient(iface.Functions)
	if src.WithZod {
		g.writeZod(iface)
	}

	if g.err != nil {
		return "", g.err
	}
	return g.b.String(), nil
}

type tsGen struct {
	b          strings.Builder
	errorEnums map[string]bool
	err        error

	// schemaNames maps a user-defined type name to the const the schemas
	// section declares for it, decided before anything is written so
	// every reference resolves to the same identifier.
	schemaNames map[string]string
}

func (g *tsGen) writeDoc(indent, doc string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	// A "*/" in a doc string would end the comment early.
	doc = strings.ReplaceAll(doc, "*/", "*\\/")
	g.b.WriteString(indent + "/**\n")
	for _, line := range strings.Split(doc, "\n") {
		g.b.WriteString(strings.TrimRight(indent+" * "+line, " ") + "\n")
	}
	g.b.WriteString(indent + " */\n")
}

func (g *tsGen) writeStruct(s model.Struct) {
	g.b.WriteString("\n")
	g.writeDoc("", s.Doc)
	name := typeName(s.Name)
	if s.IsTuple {
		parts := make([]string, len(s.Fields))
		for i, f := range s.Fields {
			parts[i] = g.tsType(f.Type)
		}
		fmt.Fprintf(&g.b, "export type %s = readonly [%s];\n", name, strings.Join(parts, ", "))
		return
	}
	fmt.Fprintf(&g.b, "export interface %s {\n", name)
	for _, f := range s.Fields {
		g.writeDoc("  ", f.Doc)
		fmt.Fprintf(&g.b, "  %s: %s;\n", propertyKey(f.Name), g.tsType(f.Type))
	}
	g.b.WriteString("}\n")
}

// writeUnion uses the SDK's tagged-object encoding: {tag, values}, where
// values is void for a unit case and a tuple of payloads otherwise.
func (g *tsGen) writeUnion(u model.Union) {
	g.b.WriteString("\n")
	g.writeDoc("", u.Doc)
	fmt.Fprintf(&g.b, "export type %s =", typeName(u.Name))
	if len(u.Cases) == 0 {
		g.b.WriteString(" never;\n")
		return
	}
	for _, c := range u.Cases {
		values := "void"
		if len(c.Values) > 0 {
			parts := make([]string, len(c.Values))
			for i, v := range c.Values {
				parts[i] = g.tsType(v)
			}
			values = "readonly [" + strings.Join(parts, ", ") + "]"
		}
		fmt.Fprintf(&g.b, "\n  | { tag: %q; values: %s }", c.Name, values)
	}
	g.b.WriteString(";\n")
}

func (g *tsGen) writeEnum(e model.Enum) {
	g.b.WriteString("\n")
	g.writeDoc("", e.Doc)
	fmt.Fprintf(&g.b, "export enum %s {\n", typeName(e.Name))
	for _, c := range e.Cases {
		g.writeDoc("  ", c.Doc)
		fmt.Fprintf(&g.b, "  %s = %d,\n", propertyKey(c.Name), c.Value)
	}
	g.b.WriteString("}\n")
}

// writeErrors emits one table of every contract error code, which is what
// the host reports and what contract.Client's Result errors carry. Codes
// from several error enums are merged; a code declared twice is an error,
// because the generated table could not say which meaning applies.
func (g *tsGen) writeErrors(enums []model.ErrorEnum) {
	type entry struct {
		code    uint32
		message string
	}
	byCode := map[uint32]entry{}
	for _, e := range enums {
		for _, c := range e.Cases {
			if prev, dup := byCode[c.Value]; dup && prev.message != c.Name {
				g.fail(fmt.Errorf("codegen: error code %d is both %s and %s", c.Value, prev.message, c.Name))
				return
			}
			byCode[c.Value] = entry{c.Value, c.Name}
		}
	}

	codes := make([]uint32, 0, len(byCode))
	for code := range byCode {
		codes = append(codes, code)
	}
	sort.Slice(codes, func(i, j int) bool { return codes[i] < codes[j] })

	g.b.WriteString("\n/** Contract error codes, as reported by the host. */\n")
	g.b.WriteString("export const Errors: Record<number, { message: string }> = {\n")
	for _, code := range codes {
		fmt.Fprintf(&g.b, "  %d: { message: %q },\n", code, byCode[code].message)
	}
	g.b.WriteString("};\n")
}

func (g *tsGen) writeClient(fns []model.Function) {
	g.b.WriteString("\n/** Typed methods of the contract. Each one simulates on call; sign and send the result to submit. */\n")
	g.b.WriteString("export interface Client {\n")
	for _, fn := range fns {
		// Arguments are properties of the single args object, so JSDoc
		// must use args.<name> to attach hover documentation correctly.
		// Reuse writeDoc for escaping */ and formatting multiline docs.
		var docs []string
		if strings.TrimSpace(fn.Doc) != "" {
			docs = append(docs, strings.TrimSpace(fn.Doc))
		}
		for _, in := range fn.Inputs {
			if doc := strings.TrimSpace(in.Doc); doc != "" {
				lines := strings.Split(doc, "\n")
				for i := 1; i < len(lines); i++ {
					lines[i] = strings.TrimSpace(lines[i])
				}
				docs = append(docs, "@param args."+in.Name+" "+strings.Join(lines, "\n"))
			}
		}
		g.writeDoc("  ", strings.Join(docs, "\n\n"))

		ret := "null"
		if len(fn.Outputs) > 0 {
			ret = g.tsType(fn.Outputs[0])
		}
		result := "Promise<sdk.AssembledTransaction<" + ret + ">>"

		if len(fn.Inputs) == 0 {
			fmt.Fprintf(&g.b, "  %s(options?: sdk.MethodOptions): %s;\n", propertyKey(fn.Name), result)
			continue
		}
		params := make([]string, len(fn.Inputs))
		for i, in := range fn.Inputs {
			params[i] = propertyKey(in.Name) + ": " + g.tsType(in.Type)
		}
		fmt.Fprintf(&g.b, "  %s(args: { %s }, options?: sdk.MethodOptions): %s;\n",
			propertyKey(fn.Name), strings.Join(params, "; "), result)
	}
	g.b.WriteString("}\n")

	g.b.WriteString(`
/**
 * Connect to the contract. The SDK reads its spec from the network and
 * builds the methods; this narrows them to the types above. contractId
 * defaults to the contract this file was generated from.
 */
export function connect(
  options: Omit<sdk.ClientOptions, "contractId"> & { contractId?: string },
): Promise<sdk.Client & Client> {
  return sdk.Client.from<Client>({ ...options, contractId: options.contractId ?? contractId });
}

/**
 * assertSameWasm warns when the deployed contract no longer runs the
 * interface this client was generated for: an upgrade may have removed
 * or changed the functions above, and the old method names would fail
 * deep inside a call. Pass the contract's live wasm_hash — SoroVault's
 * GET /api/contracts/{id} returns it — and the function returns whether
 * the client still matches. Calling it is entirely optional: nothing
 * happens without it, so offline use keeps working.
 */
export function assertSameWasm(liveHash: string): boolean {
  if (liveHash === wasmHash) return true;
  console.warn(
    "[sorovault] contract " + contractId + " changed: this client was generated" +
      " for WASM " + wasmHash + " but the live hash is " + liveHash + ". Regenerate the client.",
  );
  return false;
}
`)
}

// writeZod emits runtime Zod schemas for the declared user-defined types
// and every function's argument list, so a frontend can validate a value
// before it reaches the network. It mirrors tsType's decisions: a value
// that satisfies the type declarations also passes the schema.
//
// References between schemas go through z.lazy, which keeps an arbitrary
// definition order legal in top-level consts and makes recursion safe
// without the generator needing to reason about cycles. Error enums are
// skipped: as values they are their numeric code, which the u32 schema
// already covers.
func (g *tsGen) writeZod(iface *model.Interface) {
	// Decide every schema's const name up front, in the order the
	// section declares them, so references (and collisions, which get a
	// trailing underscore) resolve to what actually ends up in the file.
	names := map[string]bool{}
	take := func(base string) string {
		name := base
		for names[name] {
			name += "_"
		}
		names[name] = true
		return name
	}
	g.schemaNames = map[string]string{}
	for _, s := range sortedBy(iface.Types.Structs, func(s model.Struct) string { return s.Name }) {
		g.schemaNames[s.Name] = take(typeName(s.Name) + "Schema")
	}
	for _, u := range sortedBy(iface.Types.Unions, func(u model.Union) string { return u.Name }) {
		g.schemaNames[u.Name] = take(typeName(u.Name) + "Schema")
	}
	for _, e := range sortedBy(iface.Types.Enums, func(e model.Enum) string { return e.Name }) {
		g.schemaNames[e.Name] = take(typeName(e.Name) + "Schema")
	}

	g.b.WriteString("\n/**\n * Runtime validators for the types above (Zod 3). Values that decode\n * into the SDK's types pass these, so a frontend can check arguments\n * before building a transaction.\n */\n")

	for _, s := range sortedBy(iface.Types.Structs, func(s model.Struct) string { return s.Name }) {
		if s.IsTuple {
			parts := make([]string, len(s.Fields))
			for i, f := range s.Fields {
				parts[i] = g.zodType(f.Type)
			}
			fmt.Fprintf(&g.b, "export const %s = z.tuple([%s]);\n", g.schemaNames[s.Name], strings.Join(parts, " "))
			continue
		}
		fmt.Fprintf(&g.b, "export const %s = z.object({\n", g.schemaNames[s.Name])
		for _, f := range s.Fields {
			fmt.Fprintf(&g.b, "  %s: %s,\n", propertyKey(f.Name), g.zodType(f.Type))
		}
		g.b.WriteString("});\n")
	}

	for _, u := range sortedBy(iface.Types.Unions, func(u model.Union) string { return u.Name }) {
		if len(u.Cases) == 0 {
			fmt.Fprintf(&g.b, "export const %s = z.never();\n", g.schemaNames[u.Name])
			continue
		}
		if len(u.Cases) == 1 {
			fmt.Fprintf(&g.b, "export const %s = %s;\n", g.schemaNames[u.Name], g.zodCase(u.Cases[0]))
			continue
		}
		fmt.Fprintf(&g.b, "export const %s = z.union([\n", g.schemaNames[u.Name])
		for _, c := range u.Cases {
			fmt.Fprintf(&g.b, "  %s,\n", g.zodCase(c))
		}
		g.b.WriteString("]);\n")
	}

	for _, e := range sortedBy(iface.Types.Enums, func(e model.Enum) string { return e.Name }) {
		// The cases were declared as a TypeScript enum above, so the
		// schema validates against the same mapping of value to meaning.
		fmt.Fprintf(&g.b, "export const %s = z.nativeEnum(%s);\n", g.schemaNames[e.Name], typeName(e.Name))
	}

	for _, fn := range iface.Functions {
		fmt.Fprintf(&g.b, "export const %s = z.object({\n", take(typeName(fn.Name)+"ArgsSchema"))
		for _, in := range fn.Inputs {
			fmt.Fprintf(&g.b, "  %s: %s,\n", propertyKey(in.Name), g.zodType(in.Type))
		}
		g.b.WriteString("});\n")
	}
}

// zodCase renders one union case: the SDK's tagged-object encoding.
func (g *tsGen) zodCase(c model.UnionCase) string {
	if len(c.Values) == 0 {
		return fmt.Sprintf("z.object({ tag: z.literal(%q), values: z.undefined() })", c.Name)
	}
	parts := make([]string, len(c.Values))
	for i, v := range c.Values {
		parts[i] = g.zodType(v)
	}
	return fmt.Sprintf("z.object({ tag: z.literal(%q), values: z.tuple([%s]) })", c.Name, strings.Join(parts, " "))
}

// zodType maps an interface type onto its Zod schema expression. Scalar
// widths are enforced exactly: the two-sided bounds of every integer kind
// and the exact length of fixed byte arrays.
//
// The SDK represents timepoints and durations as u64 bigints, and an
// error enum used as a value as its numeric u32 code, so both use the
// schemas of the kinds they stand for.
func (g *tsGen) zodType(t model.Type) string {
	switch t.Kind {
	case model.KindVal:
		return "z.any()"
	case model.KindBool:
		return "z.boolean()"
	case model.KindVoid:
		return "z.undefined()"
	case model.KindError, model.KindMap, model.KindResult:
		// Host-owned shapes (error payloads, SDK map and result wrappers):
		// anything they hand over is accepted, because inventing their
		// structure here would reject values the SDK itself produces.
		return "z.any()"
	case model.KindU32:
		return "z.number().int().min(0).max(4294967295)"
	case model.KindI32:
		return "z.number().int().min(-2147483648).max(2147483647)"
	case model.KindU64, model.KindTimepoint, model.KindDuration:
		return "z.bigint().min(0n).max((1n << 64n) - 1n)"
	case model.KindI64:
		return "z.bigint().min(-(1n << 63n)).max((1n << 63n) - 1n)"
	case model.KindU128:
		return "z.bigint().min(0n).max((1n << 128n) - 1n)"
	case model.KindI128:
		return "z.bigint().min(-(1n << 127n)).max((1n << 127n) - 1n)"
	case model.KindU256:
		return "z.bigint().min(0n).max((1n << 256n) - 1n)"
	case model.KindI256:
		return "z.bigint().min(-(1n << 255n)).max((1n << 255n) - 1n)"
	case model.KindBytes:
		return "z.custom<Buffer>((v) => Buffer.isBuffer(v))"
	case model.KindBytesN:
		return fmt.Sprintf("z.custom<Buffer>((v) => Buffer.isBuffer(v) && v.length === %d)", t.N)
	case model.KindString, model.KindSymbol:
		return "z.string()"
	case model.KindAddress:
		// A strkey address is 56 characters, C for a contract or G for an
		// account, over the base32 strkey alphabet.
		return "z.string().regex(/^[CG][A-Z2-7]{55}$/, \"not a Stellar address\")"
	case model.KindMuxedAddress:
		return "z.string().regex(/^[CM][A-Z2-7]{55}$/, \"not a Stellar muxed address\")"
	case model.KindOption:
		return g.zodChild(t.Inner) + ".optional()"
	case model.KindVec:
		return "z.array(" + g.zodChild(t.Element) + ")"
	case model.KindTuple:
		parts := make([]string, len(t.Elements))
		for i := range t.Elements {
			parts[i] = g.zodType(t.Elements[i])
		}
		return "z.tuple([" + strings.Join(parts, " ") + "])"
	case model.KindUDT:
		if g.errorEnums[t.Name] {
			return "z.number().int().min(0).max(4294967295)"
		}
		if g.schemaNames[t.Name] == "" {
			g.fail(fmt.Errorf("codegen: type %q is referenced but never declared", t.Name))
			return "z.any()"
		}
		// Cross-references go through z.lazy, so a schema can be declared
		// in any order and recursion stays legal in top-level consts.
		return fmt.Sprintf("z.lazy(() => %s)", g.schemaNames[t.Name])
	default:
		g.fail(fmt.Errorf("codegen: unsupported type kind %q", t.Kind))
		return "z.any()"
	}
}

func (g *tsGen) zodChild(t *model.Type) string {
	if t == nil {
		g.fail(fmt.Errorf("codegen: container type is missing its element type"))
		return "z.any()"
	}
	return g.zodType(*t)
}

// tsType maps an interface type onto its TypeScript form.
func (g *tsGen) tsType(t model.Type) string {
	switch t.Kind {
	case model.KindVal:
		return "any"
	case model.KindBool:
		return "boolean"
	case model.KindVoid:
		return "void"
	case model.KindError:
		return "sdk.ErrorMessage"
	case model.KindU32, model.KindI32, model.KindU64, model.KindI64,
		model.KindU128, model.KindI128, model.KindU256, model.KindI256:
		return "sdk." + string(t.Kind)
	case model.KindTimepoint:
		return "sdk.Timepoint"
	case model.KindDuration:
		return "sdk.Duration"
	case model.KindBytes, model.KindBytesN:
		return "Buffer"
	case model.KindString, model.KindSymbol, model.KindAddress, model.KindMuxedAddress:
		return "string"
	case model.KindOption:
		return "sdk.Option<" + g.child(t.Inner) + ">"
	case model.KindVec:
		return "Array<" + g.child(t.Element) + ">"
	case model.KindMap:
		return "Map<" + g.child(t.Key) + ", " + g.child(t.Value) + ">"
	case model.KindResult:
		// The SDK's Result carries an ErrorMessage, not the contract's
		// error enum; the codes are in Errors.
		return "sdk.Result<" + g.child(t.Ok) + ">"
	case model.KindTuple:
		parts := make([]string, len(t.Elements))
		for i := range t.Elements {
			parts[i] = g.tsType(t.Elements[i])
		}
		return "readonly [" + strings.Join(parts, ", ") + "]"
	case model.KindUDT:
		if g.errorEnums[t.Name] {
			// An error enum used as a value is its numeric code.
			return "sdk.u32"
		}
		return typeName(t.Name)
	default:
		g.fail(fmt.Errorf("codegen: unsupported type kind %q", t.Kind))
		return "unknown"
	}
}

func (g *tsGen) child(t *model.Type) string {
	if t == nil {
		g.fail(fmt.Errorf("codegen: container type is missing its element type"))
		return "unknown"
	}
	return g.tsType(*t)
}

func (g *tsGen) fail(err error) {
	if g.err == nil {
		g.err = err
	}
}

// typeName is the TypeScript name for a user-defined type.
func typeName(name string) string {
	if reservedTypeNames[name] {
		return name + "_"
	}
	if !identifier.MatchString(name) {
		return fmt.Sprintf("ContractType_%x", name)
	}
	return name
}

// propertyKey quotes a key that is not a plain identifier.
func propertyKey(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	return strconv.Quote(name)
}

// oneLine keeps a header value from breaking out of its comment.
func oneLine(s string) string {
	return strings.NewReplacer("\n", " ", "\r", " ").Replace(s)
}

// sortedBy returns a copy of items ordered by key, so output is stable
// regardless of the order the spec declared things in.
func sortedBy[T any](items []T, key func(T) string) []T {
	out := append([]T(nil), items...)
	sort.SliceStable(out, func(i, j int) bool { return key(out[i]) < key(out[j]) })
	return out
}
