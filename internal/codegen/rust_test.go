package codegen_test

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/soroworks/sorovault/internal/codegen"
	"github.com/soroworks/sorovault/internal/model"
)

func TestRustRendersTypesAndClient(t *testing.T) {
	t.Parallel()

	iface := &model.Interface{
		ABIVersion: model.ABIVersion,
		Types: model.Types{
			Structs: []model.Struct{{Name: "Proposal", Fields: []model.StructField{
				{Name: "id", Type: model.Scalar(model.KindU32)},
				{Name: "title", Type: model.Scalar(model.KindString)},
			}}},
			Unions: []model.Union{{Name: "Vote", Cases: []model.UnionCase{{Name: "Yes"}, {Name: "No"}}}},
			Enums:  []model.Enum{{Name: "Status", Cases: []model.EnumCase{{Name: "Open", Value: 0}, {Name: "Closed", Value: 1}}}},
		},
	}
	src := codegen.Source{ContractID: "CDZZ", Network: "testnet", WasmHash: "abc123"}

	got, err := codegen.Rust(iface, src)
	require.NoError(t, err)

	for _, want := range []string{
		"// Code generated by SoroVault from contract CDZZ on testnet.",
		"// Interface version (WASM hash): abc123",
		"// User-defined types:",
		"pub struct Proposal {\n\tid: String,\n\ttitle: String,\n}",
		"pub enum Vote {\n\tYes,\n\tNo,\n}",
		"pub enum Status {\n\tOpen = 0,\n\tClosed = 1,\n}",
		"pub struct Client {",
		"impl Client {",
		"pub fn connect(address: String) -> Self {",
		"pub fn address(&self) -> &String {",
		"pub fn call(&self, fn_name: String, args: Vec<u8>)",
	} {
		assert.Contains(t, got, want)
	}
	assert.Equal(t, strings.Count(got, "{"), strings.Count(got, "}"), "braces balance")
}

func TestRustOmitsTheTypesHeaderWithoutTypes(t *testing.T) {
	t.Parallel()

	got, err := codegen.Rust(&model.Interface{ABIVersion: model.ABIVersion}, codegen.Source{ContractID: "CDZZ"})
	require.NoError(t, err)
	assert.NotContains(t, got, "// User-defined types:")
	assert.Contains(t, got, "impl Client {")
}
