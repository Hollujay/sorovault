// freshClient and upgradedClient stand in for what the generator emits:
// the constants embedded in the header plus the Client interface whose
// methods are what the diff reports.
const freshClient = `// Code generated by SoroVault. DO NOT EDIT.

import { Buffer } from "buffer";
import * as sdk from "@stellar/stellar-sdk/contract";

export const contractId = "CABC";
export const networkName = "testnet";
export const wasmHash = "oldhash";

export interface Client {
  initialize(options?: sdk.MethodOptions): Promise<sdk.AssembledTransaction<null>>;
  vote(args: { nullifier: Buffer }, options?: sdk.MethodOptions): Promise<sdk.AssembledTransaction<sdk.u32>>;
}
`

const upgradedClient = `// Code generated by SoroVault. DO NOT EDIT.

import { Buffer } from "buffer";
import * as sdk from "@stellar/stellar-sdk/contract";

export const contractId = "CABC";
export const networkName = "testnet";
export const wasmHash = "newhash";

export interface Client {
  initialize(options?: sdk.MethodOptions): Promise<sdk.AssembledTransaction<null>>;
  vote(args: { nullifier: Buffer; reason: string }, options?: sdk.MethodOptions): Promise<sdk.AssembledTransaction<sdk.u32>>;
  tally(options?: sdk.MethodOptions): Promise<sdk.AssembledTransaction<sdk.u64>>;
}
`

// vaultStub serves the two read endpoints check-client asks for: the
// contract's live wasm_hash and the client the server would generate now.
type vaultStub struct {
	wasmHash  string
	clientSrc string
	status    int
}

func serveVault(t *testing.T, v vaultStub) *httptest.Server {
	t.Helper()
	s := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasSuffix(r.URL.Path, "/client.ts") {
			w.WriteHeader(v.status)
			_, _ = w.Write([]byte(v.clientSrc))
			return
		}
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(v.status)
		_ = json.NewEncoder(w).Encode(map[string]string{"wasm_hash": v.wasmHash})
	}))
	t.Cleanup(s.Close)
	return s
}

// writeCommitted puts a generated client where the command can point at it.
func writeCommitted(t *testing.T, src string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "client.ts")
	require.NoError(t, os.WriteFile(path, []byte(src), 0o600))
	return path
}

// runCheck executes check-client against args and returns what it printed.
func runCheck(args ...string) (string, error) {
	var buf bytes.Buffer
	cmd := newCheckClientCmd()
	cmd.SetOut(&buf)
	cmd.SetErr(&buf)
	cmd.SetArgs(args)
	err := cmd.Execute()
	return buf.String(), err
}

func TestCheckClientFresh(t *testing.T) {
	t.Parallel()

	server := serveVault(t, vaultStub{wasmHash: "oldhash", clientSrc: freshClient, status: http.StatusOK})
	out, err := runCheck("--api", server.URL, "--contract", "CABC", writeCommitted(t, freshClient))
	require.NoError(t, err)
	assert.Contains(t, out, "up to date with oldhash")
}

func TestCheckClientReportsAnUpgrade(t *testing.T) {
	t.Parallel()

	server := serveVault(t, vaultStub{wasmHash: "newhash", clientSrc: upgradedClient, status: http.StatusOK})
	out, err := runCheck("--api", server.URL, "--contract", "CABC", writeCommitted(t, freshClient))
	require.Error(t, err)
	require.True(t, errors.Is(err, errPrinted), "the reason list should already be printed")

	assert.Contains(t, out, "generated for oldhash, the live hash is newhash")
	assert.Contains(t, out, "tally: added to the interface")
	assert.Contains(t, out, "vote: signature changed")
	assert.NotContains(t, out, "initialize:", "an unchanged method is not a finding")
	assert.Contains(t, out, "is stale; regenerate it")
}

func TestCheckClientRejectsTheWrongContract(t *testing.T) {
	t.Parallel()

	server := serveVault(t, vaultStub{wasmHash: "oldhash", clientSrc: freshClient, status: http.StatusOK})
	path := writeCommitted(t, freshClient)

	out, err := runCheck("--api", server.URL, "--contract", "CXYZ", path)
	require.Error(t, err)
	require.True(t, errors.Is(err, errPrinted))
	assert.Contains(t, out, "the client points at contract CABC, but --contract says CXYZ")
	assert.NotContains(t, out, "up to date", "the check stops before trusting the pin")
}

func TestCheckClientExplainsAMissingHash(t *testing.T) {
	t.Parallel()

	older := strings.Replace(freshClient, `export const wasmHash = "oldhash";`+"\n", "", 1)
	out, err := runCheck("--api", "http://127.0.0.1:1", "--contract", "CABC", writeCommitted(t, older))
	require.Error(t, err)
	require.True(t, errors.Is(err, errPrinted))
	assert.Contains(t, out, "carries no wasmHash constant")
}

func TestCheckClientRejectsAnUnknownFile(t *testing.T) {
	t.Parallel()

	_, err := runCheck("--api", "http://127.0.0.1:1", "--contract", "CABC",
		writeCommitted(t, "export const nothing = true;\n"))
	require.Error(t, err)
	assert.False(t, errors.Is(err, errPrinted))
	assert.Contains(t, err.Error(), "not a SoroVault-generated client")
}

func TestCheckClientSurfacesAnUnregisteredContract(t *testing.T) {
	t.Parallel()

	// The hash lookup answers first, so a contract SoroVault does not
	// know surfaces there.
	server := serveVault(t, vaultStub{wasmHash: "x", clientSrc: "gone", status: http.StatusNotFound})
	_, err := runCheck("--api", server.URL, "--contract", "CABC", writeCommitted(t, freshClient))
	require.Error(t, err)
	assert.Contains(t, err.Error(), "answered 404")
}

func TestCheckClientSurfacesAnUnreachableServer(t *testing.T) {
	t.Parallel()

	server := serveVault(t, vaultStub{wasmHash: "oldhash", clientSrc: freshClient, status: http.StatusOK})
	server.Close() // a registry that was reachable and is not any more

	_, err := runCheck("--api", server.URL, "--contract", "CABC", writeCommitted(t, freshClient))
	require.Error(t, err)
	assert.Contains(t, err.Error(), "asking SoroVault")
}

func TestCheckClientBytesDifferWithoutAFunctionChange(t *testing.T) {
	t.Parallel()

	// Same methods, different docs: the function diff comes out empty and
	// the output says so rather than reporting nothing at all.
	moved := strings.Replace(freshClient, "import { Buffer } from \"buffer\";\n",
		"import { Buffer } from \"buffer\";\n// a comment the generator would not repeat\n", 1)
	server := serveVault(t, vaultStub{wasmHash: "oldhash", clientSrc: moved, status: http.StatusOK})
	out, err := runCheck("--api", server.URL, "--contract", "CABC", writeCommitted(t, freshClient))
	require.Error(t, err)
	assert.Contains(t, out, "no function signature changed, but the generated bytes differ")
}

func TestDeclaredMethods(t *testing.T) {
	t.Parallel()

	src := `export interface Client {
  plain(args: { n: sdk.u64 }): void;
  "quoted-name"(options?: sdk.MethodOptions): void;
  second(): void;
}
`
	names, methods := declaredMethods(src)
	assert.Equal(t, []string{"plain", "quoted-name", "second"}, names)
	assert.Len(t, methods, 3)
	assert.Contains(t, methods["quoted-name"], `"quoted-name"(options?`)

	// A file without a Client interface yields nothing rather than garbage.
	names, methods = declaredMethods("export const contractId = \"C\";\n")
	assert.Empty(t, names)
	assert.Empty(t, methods)
}
